        <section class="ceaf-conteudo">
            <div>
                <h2>O que é o CEAF?</h2>
                <p>O Componente Especializado da Assistência Farmacêutica é uma estratégia do SUS para garantir tratamentos de condições clínicas mais complexas, como doenças raras, autoimunes, esclerose múltipla, artrite reumatoide, doenças inflamatórias intestinais, psoríase grave e transplantes.</p>
            </div>

            <div class="ceaf-alerta">
                <p><strong>Um detalhe importante:</strong> "medicamento de alto custo" não é o nome oficial. O acesso depende da doença, dos critérios do PCDT, da prescrição e da avaliação da Secretaria de Saúde.</p>
            </div>

          
            <section id="passo-a-passo">
                <h2>O caminho em 4 passos</h2>
                <p>O local e o formato do pedido mudam de estado para estado. Confirme a farmácia de referência com a Secretaria de Saúde.</p>
                
                <ol class="ceaf-passos">
                    <li>
                        <h3>1. Converse com o profissional</h3>
                        <p>Leve seus exames e histórico. Se o tratamento estiver previsto no PCDT, o prescritor preencherá o LME e a receita.</p>
                    </li>
                    <li>
                        <h3>2. Separe os documentos</h3>
                        <p>Reúna documentos pessoais, Cartão SUS, comprovante de residência, receita, LME e os exames exigidos para a sua condição.</p>
                    </li>
                    <li>
                        <h3>3. Faça a solicitação</h3>
                        <p>Entregue tudo na farmácia de referência do seu estado ou envie pela plataforma oficial, quando esse serviço estiver disponível.</p>
                    </li>
                    <li>
                        <h3>4. Acompanhe e retire</h3>
                        <p>A Secretaria analisa o pedido. Com a autorização, você recebe o medicamento no local indicado e acompanha as próximas renovações.</p>
                    </li>
                </ol>
            </section>

          
            <section class="ceaf-duas-colunas">
                <div>
                    <h2>O que levar?</h2>
                    <ul>
                        <li>Documento de identificação e CPF</li>
                        <li>Cartão Nacional de Saúde (Cartão SUS)</li>
                        <li>Comprovante de residência</li>
                        <li>Receita médica dentro da validade</li>
                        <li>LME preenchido e assinado pelo prescritor</li>
                        <li>Exames e documentos previstos no PCDT</li>
                    </ul>
                    <p><small>A lista pode mudar de acordo com a doença, o medicamento e as regras da Secretaria de Saúde local.</small></p>
                </div>

                <div>
                    <h2>Renovação do tratamento</h2>
                    <p>Alguns tratamentos precisam de uma nova avaliação periódica. Não espere o medicamento acabar: confira no comprovante de dispensação a data para renovar.</p>
                    <p>Na renovação, podem ser solicitados um novo LME, receita atualizada, exames de acompanhamento e documentos pessoais.</p>
                    <p><strong>Guarde protocolos, recibos e resultados.</strong></p>
                </div>
            </section>

            
            <section>
                <h2>Medicamentos e condições</h2>
                <p>O elenco oficial é amplo e pode ser atualizado. Estes são exemplos de áreas atendidas pelo CEAF, não uma prescrição nem uma lista completa.</p>
                
                <div>
                    <h3>Doenças autoimunes</h3>
                    <p>Artrite reumatoide, lúpus e psoríase em formas previstas no PCDT podem ter opções como metotrexato, adalimumabe e outros imunobiológicos, conforme os critérios clínicos.</p>
                </div>

                <div>
                    <h3>Esclerose múltipla</h3>
                    <p>O tratamento pode envolver medicamentos modificadores da doença, como betainterferonas, acetato de glatirâmer ou fingolimode, sempre conforme avaliação especializada.</p>
                </div>

                <div>
                    <h3>Doenças raras e outras condições</h3>
                    <p>Também existem linhas para doenças raras, hepatites, doença renal, transplantados e doenças inflamatórias intestinais. A disponibilidade depende do diagnóstico e do PCDT correspondente.</p>
                </div>

                <p><strong>Não troque, comece ou pare um medicamento por conta própria.</strong> O nome, a dose e a forma de uso devem seguir a receita e a orientação da equipe de saúde.</p>
            </section>

     
